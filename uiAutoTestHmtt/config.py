# 这是在获取你当前这个项目的“绝对根目录路径”，把它存到 BASE_PATH 这个变量里
# 作用：拿到当前项目的绝对根目录，以后所有找文件的操作，都从它开始拼接

import os
BASE_PATH = os.path.dirname(__file__)

# os.path.dirname(...)：这个工具的作用是“获取上一级目录”。你把文件路径放进去，它就会把文件名砍掉，只留文件夹路径
# BASE_PATH：最终得到的结果是："D:\你的项目\uiAutoTestHmtt"。也就是你整个框架的最外层根目录
# 也就是说，日志图片等数据都需要进行存储，这个东西是帮助生成绝对路径的固定模板